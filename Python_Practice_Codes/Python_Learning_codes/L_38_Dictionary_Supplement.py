# print("字典的浅拷贝方法，copy()")
a = dict.fromkeys("EWEVDN", 1)
b = a.copy()
print(b)
# print("用in和not in判断某个键是否存在于字典中")
print("E" in b)
# print("list()可以把字典的键转化为列表，同时可使用视图对象如values把值转化为列表")
print(list(a))
print(list(a.values()))
print()
# print("iter()可以把字典的键构成一个新的迭代器，可使用视图对象改为值等")
print(iter(b))
print(list(iter(b)))
for i in iter(b):
    print(i)
print()
# print("reversed()可以的把字典的键构成一个反向迭代器，可使用视图对象改为值等")
c = dict.fromkeys("EWEVDN", 2)
print(reversed(c))
print(list(reversed(c)))
for j in reversed(c):
    print(j)