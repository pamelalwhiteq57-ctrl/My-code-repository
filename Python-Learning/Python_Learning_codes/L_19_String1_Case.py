# print("capitalize()将字符串首字母变大写，其余变小写:")
x = "eWEvDn EWEvdn"
x = x.capitalize()
print(x)
print()
# print("casefold()将所有字母变小写(通用):")
y = "eWEvDn EWEvdn"
y = y.casefold()
print(y)
print()
# print("title()将每个单词依次capitalize化:")
z = "eWEvDn EWEvdn"
z = z.title()
print(z)
print()
# print("swapcase()将每个字母大小写反转:")
a = "eWEvDn EWEvdn"
a = a.swapcase()
print(a)
print()
# print("upper()将所有字母变成大写:")
b = "eWEvDn EWEvdn"
b = b.upper()
print(b)
print()
# print("lower()将所有字母变为小写，且只能处理英文字符:")
c = "eWEvDn EWEvdn"
c = c.casefold()
print(c)