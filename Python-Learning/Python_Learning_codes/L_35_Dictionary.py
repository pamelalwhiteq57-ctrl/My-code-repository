# print("在字典中，只要提供键，就可以获取对应的值")
# print("创建字典1，用'{}'加':'来锁定对应关系(映射)")
a = {1:"A", 2:"B", 3:"C"}
print(a[1])
print("以下为创建字典的一些方法")
# print("通过写一个不存在的键，来添加这个键对应的值")
a[4] = "D"
print(a)
print()
# print("创建字典2，用dict()函数，每个参数就是一个对应的键值对，使用等号进行挂钩，其中键不能加引号")
b = dict(a=1, b=2, c=3)
print(b)
print()
# print("创建字典3，用列表作为参数，其中的每个元素是用元组包裹的键值对")
c = dict([("I", "我"), ("You", "你"), ("It", "它")])
print(c)
print()
# print("创建字典4，将方法1{}及以内的值作为参数传递给dict()，几乎不用")
d = dict({1:"A", 2:"B", 3:"C", 4:"D"})
print(d)
print()
# print("创建字典5，将以上方法混合即可")
# print("创建字典6，zip()函数，让其作为参数传递给dict()函数")
e = dict(zip(["a", "b", "c"], ["A", "B", "C"]))
print(e)
print()
# print("可直接判断俩字典是否相等")
print(a == d, a == e)