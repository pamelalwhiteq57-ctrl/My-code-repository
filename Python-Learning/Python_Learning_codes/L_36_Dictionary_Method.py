# print("fromkeys(iterable[, values])，iterable指定的可迭代对象，映射到values的值中，每个的值相同且都是values")
a = dict.fromkeys("EWEVDN", 9)
print(a)
# print("可以修改某个键对应的值")
a["E"] = 1
print(a)
# print("pop(key[, default])，用于删除指定键值对，default同样用于不存在的操作时返回的内容")
a.pop("W")
print(a)
# print("popitem()可以删除最后一个加入的键对")
a.popitem()
print(a)
# print("clear()可以只清除字典中的内容")
a.clear()
print(a)
print()
# print("update([other])方法可以批量修改键值对，可以传入一些键值对或另一个字典")
b = dict.fromkeys("EWEVDN")
print(b)
b.update({"E":1, "W":2})  # 或:
# b.update(E=1, W=2)
print(b)
print()
# print("get(key[, default])，可以查找键值对，但输入不存在的的时候可以返回default而不是报错")
print(b.get("U", "未"))
print()
# print("setdefault()，可以进行查找，若不存在，则直接将那个查找的键加上default创建为原字典的新键值对")
c = dict.fromkeys("EWEVDN", 4)
print(c.setdefault("E", 5))
print(c)
c.setdefault("e", 5)
print(c)